import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { seed, EVENT_DICTIONARY } from "../src/lib/seed";
import { all } from "../src/lib/db";
import { overview, parseFilters } from "../src/lib/metrics";
import { FIELDS } from "../src/lib/segments";

// Builds docs/DATA_DICTIONARY.md from the live schema + metric definitions (seeds a tiny temp DB).
seed({ file: path.join(fs.mkdtempSync(path.join(os.tmpdir(), "aec-dd-")), "dd.db"), customers: 300, events: 3000, quiet: true });
const tables = all<{ name: string }>("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name");
let md = "# Data dictionary\n\nGenerated by `npx tsx scripts/gen-data-dictionary.ts` from the live schema (`migrations/001_init.sql`).\n\n";
md += "## Metric definitions (Overview)\n\n| Group | Metric | Definition | Formula | Source |\n|---|---|---|---|---|\n";
const o = overview(parseFilters(new URLSearchParams({ days: "7" })));
for (const g of ["customer", "gaming", "engagement", "ai", "offers"] as const) for (const m of o[g]) md += `| ${g} | ${m.label} | ${m.definition} | \`${m.formula}\` | ${m.source} |\n`;
md += "\n## Segment fields (rule DSL whitelist)\n\n| Field | Type | Description |\n|---|---|---|\n";
for (const [k, f] of Object.entries(FIELDS)) md += `| \`${k}\` | ${f.type}${f.options ? ` (${f.options.join(", ")})` : ""} | ${f.description} |\n`;
md += "\n## Event dictionary\n\nCommon attributes: `event_id, player_id, game_id, provider_id, session_id, event_time, entry_source, platform, device_type, operating_system, app_version, loading_duration, error_code, correlation_id, properties`.\n\n| Event | Category | Required | Restricted | Description |\n|---|---|---|---|---|\n";
for (const [n, c, d, req, r] of EVENT_DICTIONARY) md += `| \`${n}\` | ${c} | ${req.join(", ")} | ${r ? "yes" : ""} | ${d} |\n`;
md += "\n## Tables\n\n";
for (const t of tables) {
  const cols = all<{ name: string; type: string; notnull: number; pk: number }>(`PRAGMA table_info(${t.name})`);
  const fks = all<{ from: string; table: string; to: string }>(`PRAGMA foreign_key_list(${t.name})`);
  md += `### ${t.name}\n\n| Column | Type | Null | Key |\n|---|---|---|---|\n`;
  for (const c of cols) { const fk = fks.find((f) => f.from === c.name); md += `| ${c.name} | ${c.type} | ${c.notnull ? "NOT NULL" : ""} | ${c.pk ? "PK" : ""}${fk ? ` → ${fk.table}.${fk.to}` : ""} |\n`; }
  md += "\n";
}
fs.writeFileSync("docs/DATA_DICTIONARY.md", md);
console.log(`${tables.length} tables documented`);
